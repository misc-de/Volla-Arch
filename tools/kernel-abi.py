#!/usr/bin/env python3
# Generates the ABI check of pkgbuilds/plinius-kmod (abicheck.c body): _Static_asserts on sizeof
# and the offset of every named member of the given structs, from the BTF of the running kernel.
# Usage: ssh root@phone cat /sys/kernel/btf/vmlinux > vmlinux.btf
#        tools/kernel-abi.py vmlinux.btf led_classdev backlight_device ... > asserts.h
import struct, sys
d = open(sys.argv[1], 'rb').read()
magic, ver, flags, hlen, toff, tlen, soff, slen = struct.unpack_from('<HBBIIIII', d, 0)
assert magic == 0xeb9f
types, strs = d[hlen + toff:hlen + toff + tlen], d[hlen + soff:hlen + soff + slen]
name = lambda o: strs[o:strs.index(b'\0', o)].decode()
T = [None]
p = 0
extra = {1: lambda v: 4, 3: lambda v: 12, 4: lambda v: 12 * v, 5: lambda v: 12 * v, 6: lambda v: 8 * v,
         13: lambda v: 8 * v, 14: lambda v: 4, 15: lambda v: 12 * v, 17: lambda v: 4, 19: lambda v: 12 * v}
while p < len(types):
    no, info, sz = struct.unpack_from('<III', types, p)
    kind, vlen, kf = (info >> 24) & 0x1f, info & 0xffff, info >> 31
    mem = []
    if kind in (4, 5):
        for i in range(vlen):
            mn, mt, mo = struct.unpack_from('<III', types, p + 12 + 12 * i)
            bits = mo >> 24 if kf else 0
            mem.append((name(mn), mo & 0xffffff if kf else mo, bits))
    T.append((kind, name(no), sz, mem))
    p += 12 + extra.get(kind, lambda v: 0)(vlen)
want = sys.argv[2:]
print('/* Generated by tools/kernel-abi.py from /sys/kernel/btf/vmlinux */')
for kind, n, sz, mem in T[1:]:
    if kind != 4 or n not in want:
        continue
    want.remove(n)
    print('_Static_assert(sizeof(struct %s) == %d, "size of %s");' % (n, sz, n))
    for mn, off, bits in mem:
        if mn and not bits and off % 8 == 0:
            print('_Static_assert(offsetof(struct %s, %s) == %d, "%s.%s");' % (n, mn, off // 8, n, mn))
if want:
    sys.exit('not in BTF: %s' % want)
