#!/bin/bash
# Creates the signing key of the [plinius] repo (docs/PAKETIERUNG.md, rule 6) and generates
# pkgbuilds/plinius-keyring from it. If the key already exists, only the package is regenerated.
#
# Usage: tools/keygen.sh [--no-passphrase]
#   Without the option gpg asks for a passphrase (pinentry); tools/publish.sh then asks for it
#   when signing. Use --no-passphrase only on a dedicated build machine that does nothing else.
#
# The key lives in $SIGN_GNUPG (default ~/.local/share/plinius/gnupg). Back up that directory:
# if it is lost, devices trust no further update until a new plinius-keyring is installed by
# other means (image, by hand). gpg puts the revocation certificate into openpgp-revocs.d/
# inside it; store that separately from the key.
set -euo pipefail
. "$(dirname "$0")/lib.sh"

pass=()
case ${1:-} in
	--no-passphrase) pass=(--passphrase '' --pinentry-mode loopback) ;;
	"") ;;
	*) die "usage: tools/keygen.sh [--no-passphrase]" ;;
esac

export GNUPGHOME=$SIGN_GNUPG
fpr=$(sign_key)
if [[ -z $fpr ]]; then
	install -d -m700 "$GNUPGHOME"
	msg "Creating the signing key in $GNUPGHOME"
	# Signing only; after five years extend it with gpg --quick-set-expire and regenerate
	# plinius-keyring (otherwise pacman rejects the signatures)
	gpg --batch "${pass[@]}" --quick-generate-key "Plinius Paketsignatur" ed25519 sign 5y
	fpr=$(sign_key)
	[[ -n $fpr ]] || die "gpg did not create a key"
else
	msg "Signing key exists: $fpr"
fi

pkg=$PKGBUILDS/plinius-keyring
mkdir -p "$pkg"
gpg --batch --armor --export "$fpr" > "$pkg/plinius.gpg"
# pacman-key --populate: fingerprint:trust level (4 = full)
echo "$fpr:4:" > "$pkg/plinius-trusted"
: > "$pkg/plinius-revoked"
ln -sfn ../../LICENSE "$pkg/LICENSE"
cat > "$pkg/plinius-keyring.install" <<'INSTALL'
post_upgrade() {
	# Only once the keyring is initialized (image/mkimage.sh runs --populate itself afterwards)
	if usr/bin/pacman-key -l >/dev/null 2>&1; then
		usr/bin/pacman-key --populate plinius
	fi
}

post_install() {
	if [ -x usr/bin/pacman-key ]; then
		post_upgrade
	fi
}
INSTALL

sums=$(cd "$pkg" && sha256sum plinius.gpg plinius-trusted plinius-revoked LICENSE | awk '{ printf "\t'"'"'%s'"'"'\n", $1 }')
cat > "$pkg/PKGBUILD" <<PKGBUILD
# Maintainer: misc-de <misc-de@users.noreply.github.com>
# Generated by tools/keygen.sh, do not edit by hand.
# Key: $fpr

pkgname=plinius-keyring
pkgver=$(date +%Y%m%d)
pkgrel=1
pkgdesc="Signing key of the Plinius package repository"
arch=(any)
license=(MIT)
install=plinius-keyring.install
source=(plinius.gpg plinius-trusted plinius-revoked LICENSE)
sha256sums=(
$sums
)

package() {
	install -Dm644 LICENSE -t "\$pkgdir/usr/share/licenses/\$pkgname"
	install -Dm644 plinius.gpg plinius-trusted plinius-revoked -t "\$pkgdir/usr/share/pacman/keyrings"
}
PKGBUILD
msg "pkgbuilds/plinius-keyring generated, now: tools/build.sh plinius-keyring (for each architecture)"
