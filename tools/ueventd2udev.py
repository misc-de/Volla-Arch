#!/usr/bin/env python3
"""Turns the device nodes of a vendor ueventd.rc into udev rules for the host.

The Android container's ueventd cannot set owners and modes under Halium (no SELinux
labels), so vendor daemons such as wlan_assistant (uid wifi) cannot open their nodes.
Halium ports generate udev rules from ueventd.rc for this; this does the same, with
the Android IDs as host users aid_<name> (udev only takes names) and without the nodes
Linux itself uses (block devices, DRM, USB, hidraw, serial adapters).

Usage: tools/ueventd2udev.py VENDOR-UEVENTD.RC > pkgbuilds/device-volla-ansuz/70-plinius-android.rules
       tools/ueventd2udev.py --sysusers > pkgbuilds/device-volla-ansuz/plinius-android.sysusers
"""
import sys

# AIDs from AOSP libcutils/include/private/android_filesystem_config.h (Android 14)
AIDS = {
    "root": 0, "system": 1000, "radio": 1001, "bluetooth": 1002, "graphics": 1003,
    "input": 1004, "audio": 1005, "camera": 1006, "log": 1007, "wifi": 1010,
    "media": 1013, "sdcard_rw": 1015, "vpn": 1016, "usb": 1018, "gps": 1021,
    "mtp": 1024, "nfc": 1027, "secure_element": 1068, "prng_seeder": 1092, "uhid": 3011,
}


def user(name):
    return "root" if name == "root" else f"aid_{name}"


# Nodes the host manages itself: keep udev's/logind's defaults
SKIP_PREFIXES = ("block/", "dri/", "bus/usb/", "log/", "hidraw", "ttyUSB", "ttyACM")


def rules(lines):
    for line in lines:
        fields = line.split()
        if len(fields) != 4 or not fields[0].startswith("/dev/"):
            continue
        path, mode, owner, group = fields
        node = path[len("/dev/"):]
        if node.startswith(SKIP_PREFIXES):
            continue
        if owner not in AIDS or group not in AIDS:
            sys.exit(f"unknown Android ID in: {line.strip()}")
        # udev matches the kernel name; nodes in a subdirectory also by subsystem
        subdir, _, name = node.rpartition("/")
        match = f'SUBSYSTEM=="{subdir}", KERNEL=="{name}"' if subdir else f'KERNEL=="{name}"'
        yield (f'ACTION=="add|change", {match}, OWNER="{user(owner)}", '
               f'GROUP="{user(group)}", MODE="{mode}"')


def sysusers():
    print("# Android IDs as host users and groups for the device nodes of the Android container")
    print("# (tools/ueventd2udev.py; IDs from AOSP android_filesystem_config.h)")
    for name, aid in AIDS.items():
        if aid:
            print(f'u {user(name)} {aid} "Android {name}" - -')


def main():
    if sys.argv[1:] == ["--sysusers"]:
        return sysusers()
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    with open(sys.argv[1]) as f:
        out = list(dict.fromkeys(rules(f)))  # ueventd.rc repeats some nodes
    print("# Generated by tools/ueventd2udev.py from the vendor's ueventd.rc: owners and modes")
    print("# of the vendor device nodes; users aid_<name> come from plinius-android.sysusers.")
    print("\n".join(out))


if __name__ == "__main__":
    main()
