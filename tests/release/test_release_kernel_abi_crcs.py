# tools/kernel-abi.py (ABI asserts from the kernel's BTF) and tools/kernel-crcs.py (modversions CRCs
# from boot.img + kallsyms), the inputs of pkgbuilds/plinius-kmod. Both run on inputs built here: a
# BTF that gcc writes for a small C file (the asserts must compile against it), a hand-made BTF
# for the encodings gcc does not produce, and a tiny kernel image with its kallsyms.

import gzip
import shutil
import struct
import subprocess
import sys

import pytest

from conftest import TOOLS

ABI = TOOLS / "kernel-abi.py"
CRCS = TOOLS / "kernel-crcs.py"


def run(script, *args):
    return subprocess.run([sys.executable, str(script), *map(str, args)], capture_output=True,
                          text=True, timeout=30)


# --- kernel-abi: BTF from gcc ---------------------------------------------------------------------

STRUCTS = """\
#include <stddef.h>
enum mode { MODE_A, MODE_B };
struct inner { char c; long l; };
union either { int i; float f; };
struct outer {
\tint a;
\tchar *p;
\tstruct inner in;
\tunsigned flag:1;
\tunsigned more:3;
\tenum mode kind;
\tunion either un;
\tint arr[3];
\tstruct { int x; };
\tint (*fn)(int, char);
};
struct outer g_outer;
union either g_either;
int use(struct outer *o) { return o->a; }
"""


def gcc_btf(tmp_path):
    if not shutil.which("gcc") or not shutil.which("objcopy"):
        pytest.skip("gcc/objcopy missing on the host")
    src = tmp_path / "structs.c"
    src.write_text(STRUCTS)
    obj = tmp_path / "structs.o"
    r = subprocess.run(["gcc", "-gbtf", "-c", str(src), "-o", str(obj)], capture_output=True,
                       text=True)
    if r.returncode != 0:
        pytest.skip(f"gcc without -gbtf: {r.stderr.strip()}")
    btf = tmp_path / "vmlinux.btf"
    subprocess.run(["objcopy", f"--dump-section=.BTF={btf}", str(obj)], check=True)
    return src, btf


def test_asserts_from_gcc_btf_compile_against_the_structs(tmp_path):
    src, btf = gcc_btf(tmp_path)
    r = run(ABI, btf, "outer", "inner")
    assert r.returncode == 0, r.stderr
    lines = r.stdout.splitlines()
    assert lines[0] == "/* Generated by tools/kernel-abi.py from /sys/kernel/btf/vmlinux */"
    assert '_Static_assert(sizeof(struct inner) == 16, "size of inner");' in lines
    assert '_Static_assert(offsetof(struct inner, l) == 8, "inner.l");' in lines
    assert '_Static_assert(offsetof(struct outer, kind) == 36, "outer.kind");' in lines
    named = [l.split(", ")[1].split(")")[0] for l in lines if "offsetof(struct outer" in l]
    # Bitfields and the anonymous struct have no offsetof
    assert named == ["a", "p", "in", "kind", "un", "arr", "fn"]
    # The generated asserts hold for the very structs: gcc checks them
    (tmp_path / "asserts.h").write_text(r.stdout)
    (tmp_path / "check.c").write_text('#include "structs.c"\n#include "asserts.h"\n')
    c = subprocess.run(["gcc", "-fsyntax-only", str(tmp_path / "check.c")], capture_output=True,
                       text=True, cwd=tmp_path)
    assert c.returncode == 0, c.stderr


def test_a_struct_missing_from_btf_stops(tmp_path):
    _, btf = gcc_btf(tmp_path)
    r = run(ABI, btf, "inner", "either", "nothing")  # a union is not a struct
    assert r.returncode == 1
    assert r.stderr.strip() == "not in BTF: ['either', 'nothing']"
    assert "sizeof(struct inner)" in r.stdout


# --- kernel-abi: hand-made BTF ----------------------------------------------------------------------

class Btf:
    def __init__(self):
        self.strings = bytearray(b"\0")
        self.types = bytearray()

    def s(self, text):
        if not text:
            return 0
        off = len(self.strings)
        self.strings += text.encode() + b"\0"
        return off

    def add(self, kind, name, size, vlen=0, kflag=0, extra=b""):
        info = (kflag << 31) | (kind << 24) | vlen
        self.types += struct.pack("<III", self.s(name), info, size) + extra

    def struct_(self, name, size, members, kflag=0, kind=4):
        extra = b"".join(struct.pack("<III", self.s(n), 1, off) for n, off in members)
        self.add(kind, name, size, len(members), kflag, extra)

    def blob(self, magic=0xeb9f):
        hdr = struct.pack("<HBBIIIII", magic, 1, 0, 24, 0, len(self.types), len(self.types),
                          len(self.strings))
        return hdr + bytes(self.types) + bytes(self.strings)


def test_hand_made_btf_bitfields_offsets_and_kinds(tmp_path):
    b = Btf()
    b.add(1, "int", 4, extra=struct.pack("<I", 32))                       # INT
    b.add(17, "tag", 1, extra=struct.pack("<i", -1))                      # DECL_TAG
    b.add(19, "e64", 8, vlen=2, extra=struct.pack("<III", b.s("X"), 1, 0) * 2)  # ENUM64
    b.add(15, ".data", 0, vlen=1, extra=struct.pack("<III", 1, 0, 4))      # DATASEC
    # kind_flag: offset in the low 24 bits, bitfield size in the high 8
    b.struct_("bits", 8, [("a", 0), ("f", (3 << 24) | 32), ("", 32), ("g", 40)], kflag=1)
    b.struct_("packed", 3, [("x", 0), ("y", 4)])                          # y at bit 4: no offsetof
    b.struct_("bits", 99, [("z", 0)])                                     # a second "bits": ignored
    b.struct_("packed", 3, [("x", 0)], kind=5)                            # a union of that name
    path = tmp_path / "btf"
    path.write_bytes(b.blob())
    r = run(ABI, path, "packed", "bits")
    assert r.returncode == 0, r.stderr
    assert r.stdout.splitlines()[1:] == [
        '_Static_assert(sizeof(struct bits) == 8, "size of bits");',
        '_Static_assert(offsetof(struct bits, a) == 0, "bits.a");',
        '_Static_assert(offsetof(struct bits, g) == 5, "bits.g");',
        '_Static_assert(sizeof(struct packed) == 3, "size of packed");',
        '_Static_assert(offsetof(struct packed, x) == 0, "packed.x");']


def test_not_btf_is_refused(tmp_path):
    path = tmp_path / "btf"
    path.write_bytes(Btf().blob(magic=0x1234))
    r = run(ABI, path, "x")
    assert r.returncode != 0 and "AssertionError" in r.stderr and r.stdout == ""


# --- kernel-crcs -----------------------------------------------------------------------------------

BASE = 0xffffffc008000000
BANNER = b"Linux version 6.1.145-plinius9 (builder@host) (gcc 14) #1 SMP PREEMPT\0"
SYMS = {  # name -> address offset from _text
    "_text": 0, "linux_banner": 0x100,
    "__start___ksymtab": 0x200, "__stop___ksymtab": 0x218,
    "__start___ksymtab_gpl": 0x240, "__stop___ksymtab_gpl": 0x24c,
    "__start___kcrctab": 0x280, "__stop___kcrctab": 0x288,
    "__start___kcrctab_gpl": 0x290, "__stop___kcrctab_gpl": 0x294,
}


def image():
    """A kernel image: banner, two exports, one GPL export (its name before the table: a
    negative PREL32 offset), their CRCs."""
    img = bytearray(0x400)
    img[0x100:0x100 + len(BANNER)] = BANNER
    names = {"foo": 0x300, "bar": 0x308, "gplsym": 0x050}
    for name, off in names.items():
        img[off:off + len(name) + 1] = name.encode() + b"\0"

    def entry(at, name):
        struct.pack_into("<iii", img, at, 0x1000 - at, names[name] - (at + 4), 0)
    entry(0x200, "foo")
    entry(0x20c, "bar")
    entry(0x240, "gplsym")
    struct.pack_into("<II", img, 0x280, 0xdeadbeef, 0x00c0ffee)
    struct.pack_into("<I", img, 0x290, 0x12345678)
    return bytes(img)


def kallsyms(path, base=BASE):
    lines = [f"{base + off if base else 0:016x} D {name}" for name, off in SYMS.items()]
    lines.insert(1, f"{base + 0x1000 if base else 0:016x} T some_function")
    lines.append(f"{base + 0x2000 if base else 0:016x} t mod_func\t[some_module]")
    path.write_text("\n".join(lines) + "\n")
    return path


ALL = ["0xdeadbeef\tfoo\tvmlinux\tEXPORT_SYMBOL\t",
       "0x00c0ffee\tbar\tvmlinux\tEXPORT_SYMBOL\t",
       "0x12345678\tgplsym\tvmlinux\tEXPORT_SYMBOL_GPL\t"]


@pytest.mark.parametrize("wrap", ["raw", "gzip", "boot.img"])
def test_crcs_of_all_exports(tmp_path, wrap):
    data = image()
    if wrap != "raw":
        data = gzip.compress(data)
    if wrap == "boot.img":
        hdr = bytearray(4096)
        hdr[:8] = b"ANDROID!"
        struct.pack_into("<I", hdr, 8, len(data))
        data = bytes(hdr) + data + b"\xff" * 512  # ramdisk etc. behind the kernel
    img = tmp_path / "boot.img"
    img.write_bytes(data)
    r = run(CRCS, img, kallsyms(tmp_path / "kallsyms"))
    assert r.returncode == 0, r.stderr
    assert r.stdout.splitlines() == ALL
    assert r.stderr.strip() == "kernel image: Linux version 6.1.145-plinius9"


def test_crcs_of_named_symbols(tmp_path):
    img = tmp_path / "Image"
    img.write_bytes(image())
    r = run(CRCS, img, kallsyms(tmp_path / "kallsyms"), "gplsym", "bar", "absent")
    assert r.returncode == 0, r.stderr
    assert r.stdout.splitlines() == [ALL[1], ALL[2]]


def test_kallsyms_without_addresses(tmp_path):
    img = tmp_path / "Image"
    img.write_bytes(image())
    r = run(CRCS, img, kallsyms(tmp_path / "kallsyms", base=0))
    assert r.returncode == 1
    assert r.stderr.strip() == "kallsyms without addresses: kptr_restrict was not 0"


def test_image_of_another_kernel(tmp_path):
    img = tmp_path / "Image"
    img.write_bytes(image().replace(b"Linux version", b"Other version"))
    r = run(CRCS, img, kallsyms(tmp_path / "kallsyms"))
    assert r.returncode == 1 and r.stdout == ""
    assert r.stderr.strip() == "the image does not belong to the running kernel"
